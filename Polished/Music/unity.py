def hz(note):
    return round(440 * (2 ** ((note - 69) / 12)))

def ms(ticks):
    return max(1, round(ticks * TEMPO_US_PER_BEAT / TICKS_PER_BEAT / 1000 * SPEED))

async def main():
    for note, ticks in SONG:
        duration = ms(ticks)
        if note < 0:
            await runloop.sleep_ms(duration)
        else:
            await sound.beep(hz(note), duration, VOLUME)

runloop.run(main())
