def midi_to_hz(note):
    return round(440 * (2 ** ((note - 69) / 12)))

def ticks_to_ms(ticks):
    return max(1, round(
        ticks * TEMPO_US_PER_BEAT / TICKS_PER_BEAT / 1000 * SPEED
    ))

async def main():
    for note, ticks in SONG:
        duration = ticks_to_ms(ticks)

        if note < 0:
            await runloop.sleep_ms(duration)
        else:
            # A tiny gap keeps repeated notes distinguishable.
            tone_ms = max(1, round(duration * 0.92))
            gap_ms = duration - tone_ms
            await sound.beep(midi_to_hz(note), tone_ms, VOLUME)
            if gap_ms:
                await runloop.sleep_ms(gap_ms)

runloop.run(main())
